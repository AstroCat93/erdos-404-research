#!/usr/bin/env python3
"""ck_C3_struct.py -- checks of the structural claims used in the proof of R3M Theorem C3 and of
Lemma C4's probability bound.  Second check_R3M instance (round 3); uses ck_lib.py only.

mode part  p seed nx nmax
  (a) n >= 2p  =>  M_n(x) < V_n(x)   (so G_l is generated by a partition into cylinders);
  (b) for x' = x + p^{V_n(x)} z: V_n(x') == V_n(x)  (each cylinder is its own atom);
  (c) B_l first event {D_(l-1)+D_l <= m_(l-1)-M_(l+1), M_(l+1) < m_(l-1)} is constant on the atom
      x + p^{m_(l-1)} Z_p (tested at x and at x + p^{m_(l-1)} z, z random, with deep gates forced
      in half of the samples); times n_l = ceil(1.25^l * 2p).
  x random with PREC digits, half of them with a forced gate v(x+i) >= s (s up to 12).
mode F1    p seed nx amax n
  (F1) for natural numbers a <= amax and every path e alive at n for x = a (DFS of ck_lib):
      v_p(a! + sum_{j in B}(a+j)!) == v_p(a!) + v_p(S_e(a)) >= v_p(a!) + V_n(a) >= v_p(a!) + v_p(n!),
  with B = {j >= 1 : e_j = 1}, using exact integer factorials (math.factorial).
mode C4    p seed ntries n_j r lmax nmc
  Lemma C4, probability part.  Atom A = x_A + p^m Z_p of G_j (m = m_j = V_{n_j}(x_A), x_A random,
  required: M_{n_j} < m).  Times n_{l+1} = ceil(r n_l).  If the hypothesis of Lemma C4 holds for
  j < l <= lmax, compare the Monte Carlo frequency (nmc samples of x in A) of
  {exists j < l <= lmax : M_{n_(l+1)} >= s_l} with the union bound
  sum_{l: n_(l+1) >= i_1} (1 + n_(l+1)/p^m) min(1, p^(m - s_l)).
  Optional 8th argument force=k>=1 plants a gate (x_A = -i_1 mod p^200, i_1 random in (n_j, n_(lmax+1)]
  for k=1, in (n_(j+k), n_(lmax+1)] for k>=2),
  so that I_A meets the time range and the bound is not trivially 0.
"""
import math
import random
import sys
from fractions import Fraction

from ck_lib import PAdic, alive_from_scratch, products


def vfact(n, p):
    s, q = 0, p
    while q <= n:
        s += n // q
        q *= p
    return s


def vint(a, p):
    if a == 0:
        return 10 ** 9
    k = 0
    while a % p == 0:
        a //= p
        k += 1
    return k


def mode_part(p, seed, nx, nmax):
    P = PAdic(p, 200)
    rnd = random.Random(seed)
    times = [2 * p]
    while times[-1] < nmax:
        times.append(math.ceil(1.25 * times[-1]))
    na = nb = nc = 0
    fa = fb = fc = 0
    for it in range(nx):
        x = rnd.randrange(P.mod)
        if it % 2:
            i = rnd.randrange(1, times[-1] + 1)
            s = rnd.randrange(1, 13)
            x = (-i + p ** s * rnd.randrange(1, p ** 150)) % P.mod
        vals = [None] + [P.v(x + i) for i in range(1, times[-1] + 1)]
        for n in range(2 * p, times[-1] + 1):
            Vn, Mn = sum(vals[1:n + 1]), max(vals[1:n + 1])
            na += 1
            fa += not (Mn < Vn)
            if n in times and Vn < 120:
                x2 = x + p ** Vn * rnd.randrange(1, p ** 30)
                nb += 1
                fb += sum(P.v(x2 + i) for i in range(1, n + 1)) != Vn
        for l in range(1, len(times) - 1):
            a, b, c = times[l - 1], times[l], times[l + 1]
            m1 = sum(vals[1:a + 1])
            if m1 >= 120:
                continue

            def ev(xx):
                vv = [None] + [P.v(xx + i) for i in range(1, c + 1)]
                ma, mc = sum(vv[1:a + 1]), sum(vv[1:c + 1])
                Mc = max(vv[1:c + 1])
                return (mc - ma) <= ma - Mc and Mc < ma
            x2 = x + p ** m1 * rnd.randrange(1, p ** 30)
            nc += 1
            fc += ev(x) != ev(x2)
    print(f"RESULT part p={p}: (a) M_n<V_n for n>=2p fails {fa}/{na}; (b) V_n constant on its cylinder "
          f"fails {fb}/{nb}; (c) B_l first event constant on G_(l-1) atoms fails {fc}/{nc}")


def mode_F1(p, seed, nx, amax, n):
    P = PAdic(p, 3 * n + 60)
    rnd = random.Random(seed)
    npaths = nfail = 0
    for _ in range(nx):
        a = rnd.randrange(1, amax + 1)
        pi, dpi, vals = products(P, a, n)
        Vn = sum(vals[1:n + 1])
        fa = math.factorial(a)
        va = vint(fa, p)
        for (b, S, dS) in alive_from_scratch(P, pi, dpi, vals, n):
            B = [j for j in range(1, n) if (b >> j) & 1]
            tot = fa + sum(math.factorial(a + j) for j in B)
            Sint = 1
            for j in B:
                Sint += math.factorial(a + j) // fa
            npaths += 1
            vt = vint(tot, p)
            if not (vt == va + vint(Sint, p) and vt >= va + Vn >= va + vfact(n, p)):
                nfail += 1
    print(f"RESULT F1 p={p} n={n}: natural-number paths checked {npaths}, failures {nfail}")


def mode_C4(p, seed, natoms, nj, r, lmax, nmc, force=0):
    P = PAdic(p, 400)
    rnd = random.Random(seed)
    times = [nj]
    while len(times) < lmax + 2:
        times.append(math.ceil(r * times[-1]))
    used = 0
    worst = 0.0
    viol = 0
    lines = []
    tries = 0
    bounds = []
    while tries < natoms:
        tries += 1
        xA = rnd.randrange(P.mod)
        if force:
            # plant a gate: x_A = -i1 + p^200 y with i1 random in (n_j, n_(lmax+1)], so i1 is in I_A
            lo = nj if force == 1 else times[force]
            xA = (-rnd.randrange(lo + 1, times[-1] + 1) + p ** 200 * rnd.randrange(1, p ** 100)) % P.mod
        vals = [None] + [P.v(xA + i) for i in range(1, times[-1] + 1)]
        m = sum(vals[1:nj + 1])
        if not max(vals[1:nj + 1]) < m:
            continue
        xA %= p ** m
        IA = [i for i in range(1, times[-1] + 1) if (xA + i) % p ** m == 0]
        sl = {}
        ok = True
        for l in range(1, lmax + 1):
            a, c = times[l - 1], times[l + 1]
            gam = 2 * vfact(a, p) - Fraction(c, p - 1)
            sl[l] = math.floor(gam / 2) + 1
            for i in range(1, c + 1):
                if i not in IA and P.v(xA + i) >= sl[l]:
                    ok = False
        if not ok:
            continue
        used += 1
        i1 = IA[0] if IA else 10 ** 18
        bound = 0.0
        for l in range(1, lmax + 1):
            c = times[l + 1]
            if c >= i1:
                bound += (1 + c / p ** m) * min(1.0, float(p) ** (m - sl[l]))
        hits = 0
        for _ in range(nmc):
            x = xA + p ** m * rnd.randrange(p ** 300)
            hit = False
            for l in range(1, lmax + 1):
                c = times[l + 1]
                if max(P.v(x + i) for i in range(1, c + 1)) >= sl[l]:
                    hit = True
                    break
            hits += hit
        freq = hits / nmc
        bounds.append(bound)
        se = math.sqrt(max(freq * (1 - freq), 1.0 / nmc) / nmc)
        if freq > bound + 4 * se:
            viol += 1
        lines.append(f"  atom m={m} i1={i1 if IA else 'none<='+str(times[-1])} freq={freq:.4f} bound={bound:.4g}")
    for t in lines[:12]:
        print(t)
    bounds.sort()
    med = bounds[len(bounds) // 2] if bounds else float("nan")
    small = sum(1 for t in bounds if t < 0.01)
    print(f"RESULT C4prob p={p} n_j={nj} r={r} lmax={lmax}: atoms (x_A random, M_nj < m) meeting the "
          f"hypothesis {used} of {tries} tried; MC frequency above union bound (+4 s.e.) in {viol}; "
          f"median bound {med:.3g}; bound < 0.01 for {small}/{used}")


def main():
    mode = sys.argv[1]
    a = sys.argv[2:]
    if mode == "part":
        mode_part(*(int(t) for t in a[:4]))
    elif mode == "F1":
        mode_F1(*(int(t) for t in a[:5]))
    elif mode == "C4":
        mode_C4(int(a[0]), int(a[1]), int(a[2]), int(a[3]), float(a[4]), int(a[5]), int(a[6]),
                int(a[7]) if len(a) > 7 else 0)


if __name__ == "__main__":
    main()
